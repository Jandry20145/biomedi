    CONSTRAINT ck_dental_consultations_closed_fields CHECK (
        (lifecycle_status = 'DRAFT' AND closed_at IS NULL AND closed_by IS NULL)
        OR lifecycle_status = 'CLOSED'
    )
);
CREATE INDEX idx_dental_consultations_record_date
    ON dental_consultations(clinical_record_id, consultation_date DESC, id DESC);
CREATE INDEX idx_dental_consultations_date ON dental_consultations(consultation_date);
CREATE INDEX idx_dental_consultations_record_lifecycle
    ON dental_consultations(clinical_record_id, lifecycle_status, consultation_date DESC);

CREATE TABLE vital_signs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL CONSTRAINT uk_vital_signs_consultation UNIQUE
        CONSTRAINT fk_vital_signs_consultation REFERENCES dental_consultations(id),
    systolic_bp SMALLINT NULL,
    diastolic_bp SMALLINT NULL,
    heart_rate SMALLINT NULL,
    respiratory_rate SMALLINT NULL,
    temperature_c NUMERIC(4,1) NULL,
    oxygen_saturation NUMERIC(5,2) NULL,
    weight_kg NUMERIC(6,2) NULL,
    height_cm NUMERIC(5,2) NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL CONSTRAINT fk_vital_signs_created_by REFERENCES users(id),
    updated_by BIGINT NULL CONSTRAINT fk_vital_signs_updated_by REFERENCES users(id),
    CONSTRAINT ck_vital_signs_oxygen CHECK (oxygen_saturation IS NULL OR oxygen_saturation BETWEEN 0 AND 100),
    CONSTRAINT ck_vital_signs_positive CHECK (
        (systolic_bp IS NULL OR systolic_bp > 0) AND (diastolic_bp IS NULL OR diastolic_bp > 0)
        AND (heart_rate IS NULL OR heart_rate > 0) AND (respiratory_rate IS NULL OR respiratory_rate > 0)
        AND (weight_kg IS NULL OR weight_kg > 0) AND (height_cm IS NULL OR height_cm > 0)
        AND (temperature_c IS NULL OR temperature_c > 0)
    )
);

CREATE TABLE diagnoses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL CONSTRAINT fk_diagnoses_consultation REFERENCES dental_consultations(id),
    description VARCHAR(500) NOT NULL,
    icd10_code VARCHAR(20) NULL,
    affected_teeth VARCHAR(255) NULL,
    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL CONSTRAINT fk_diagnoses_created_by REFERENCES users(id),
    CONSTRAINT ck_diagnoses_priority CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT'))
);
CREATE INDEX idx_diagnoses_consultation ON diagnoses(consultation_id, is_primary);

