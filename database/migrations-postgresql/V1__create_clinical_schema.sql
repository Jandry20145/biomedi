    consultation_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    consultation_type VARCHAR(60) NOT NULL DEFAULT 'GENERAL',
    lifecycle_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    reason TEXT NOT NULL,
    current_illness TEXT NULL,
    observations TEXT NULL,
    facial_symmetry TEXT NULL,
    lymph_nodes TEXT NULL,
    temporomandibular_joint TEXT NULL,
    mouth_opening TEXT NULL,
    facial_pain TEXT NULL,
    lips TEXT NULL,
    soft_tissues TEXT NULL,
    extraoral_observations TEXT NULL,
    oral_mucosa TEXT NULL,
    tongue TEXT NULL,
    palate TEXT NULL,
    mouth_floor TEXT NULL,
    gums TEXT NULL,
    periodontium TEXT NULL,
    oral_hygiene TEXT NULL,
    occlusion TEXT NULL,
    saliva TEXT NULL,
    lesions TEXT NULL,
    intraoral_observations TEXT NULL,
    treatment TEXT NULL,
    medication TEXT NULL,
    evolution TEXT NULL,
    recommendations TEXT NULL,
    next_control_date DATE NULL,
    closed_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
    closed_by BIGINT NULL CONSTRAINT fk_dental_consultations_closed_by REFERENCES users(id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
