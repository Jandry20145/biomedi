CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL CONSTRAINT uk_roles_code UNIQUE,
    name VARCHAR(80) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL CONSTRAINT fk_users_role REFERENCES roles(id),
    username VARCHAR(80) NOT NULL CONSTRAINT uk_users_username UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    first_names VARCHAR(120) NOT NULL,
    last_names VARCHAR(120) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinical_record_number VARCHAR(40) NOT NULL CONSTRAINT uk_patients_clinical_record_number UNIQUE,
    identification VARCHAR(40) NOT NULL CONSTRAINT uk_patients_identification UNIQUE,
    first_names VARCHAR(120) NOT NULL,
    last_names VARCHAR(120) NOT NULL,
    birth_date DATE NOT NULL CONSTRAINT ck_patients_birth_date CHECK (birth_date <= CURRENT_DATE),
    sex VARCHAR(30) NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(160) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMP(6) WITH TIME ZONE NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL CONSTRAINT fk_patients_created_by REFERENCES users(id),
    updated_by BIGINT NULL CONSTRAINT fk_patients_updated_by REFERENCES users(id),
    CONSTRAINT ck_patients_soft_delete CHECK (
        (active = TRUE AND deleted_at IS NULL) OR (active = FALSE AND deleted_at IS NOT NULL)
    )
);
CREATE INDEX idx_patients_first_names ON patients(first_names);
CREATE INDEX idx_patients_last_names ON patients(last_names);
CREATE INDEX idx_patients_name_search ON patients(last_names, first_names);

CREATE TABLE clinical_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL CONSTRAINT uk_clinical_records_patient UNIQUE
        CONSTRAINT fk_clinical_records_patient REFERENCES patients(id),
    opened_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL CONSTRAINT fk_clinical_records_created_by REFERENCES users(id),
    updated_by BIGINT NULL CONSTRAINT fk_clinical_records_updated_by REFERENCES users(id),
    CONSTRAINT ck_clinical_records_status CHECK (status IN ('ACTIVE','CLOSED'))
);

CREATE TABLE clinical_backgrounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
